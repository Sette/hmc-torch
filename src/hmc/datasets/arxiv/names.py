_LOWER = {k.lower(): v for k, v in ARXIV_NAMES.items()}


def arxiv_label_name(code: str) -> str:
    """Readable name of an arXiv code (case-insensitive); the code if unknown."""
    return _LOWER.get(code.lower(), code)


def arxiv_label_names(codes) -> dict[str, str]:
    """``{code: name}`` for every code except the root."""
    return {c: arxiv_label_name(c) for c in codes if c != "root"}
